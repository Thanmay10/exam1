require(foreign)
require(MASS)
url="https://stats.idre.ucla.edu/stat/data/binary.csv"
ad=read.csv(url)
dim(ad)
head(ad)
model=glm(admit~gre+gpa+rank,data=ad,family=binomial())
summary(model)
fitted(model)
predicted=ifelse(predict(model,type="response")>0.5,1,0)
print(predicted)
install.packages("caret")
library(caret)
cm=confusionMatrix(data=factor(predicted),reference=factor(ad$admit),positive="1")
print(cm)