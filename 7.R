cars=data.frame(Cid=1:5,Price=c(10,20,30,40,50),Age=c(1,2,4,5,5),Milage=c(90,78,67,45,34))
print(cars)
model=lm(Price~Age+Milage,data=cars)
summary(model)
coef(model)
residuals(model)
pred=predict(model)
print(pred)
install.packages("scatterplot3d")
library(scatterplot3d)
s3d=scatterplot3d(cars$Age,cars$Milage,cars$Price,main="Multiple linear regression",xlab="Age",ylab="Milage",zlab="Price",pch=19)
s3d$plane3d(model)
plot(cars$Price,pred,main="Actual vs predicted",xlab="actual",ylab="predicted",col="pink",pch=19)
abline(0,1,color="red",lwd=2)
