um=data.frame(R=c(10,20,30,40,50,60),U=c(15,20,25,30,40,50))
model=lm(U~R,data=um)
summary(model)
pred=predict(model)
print(pred)
new=data.frame(R=50)
new_pred=predict(model,new)
print(new_pred)
plot(um$R,um$U,main="Umbrellas sold",xlab="Rainfall",ylab="Umbrellas sold",col="green",pch=19)
abline(model,col="red",lwd=2)