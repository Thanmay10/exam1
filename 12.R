data=data.frame(Hours=c(1,2,3,4,5),Score=c(10,20,30,40,50))
print(data)
model=lm(Score~Hours,data=data)
summary(model)
pred=predict(model)
print(pred)
new=data.frame(Hours=7)
newpre=predict(model,new)
print(newpre)
plot(data$Score,data$Hours,main="Linear regression",pch=19,col="blue",xlab="Score",ylab="Hours")
abline(model,col="red",lwd=2)