install.packages("dplyr")
library(dplyr)
data=data.frame(Name=c("A","B",NA,"C","D"),Age=1:5,Sal=c(10,20,NA,40,50),City=c("Hyd","del","del","rus","NY"))
print(data)
is.na(data)
library(tidyr)
replace=replace_na(data,list(Name="C",Sal=30))
print("Replaced values:")
print(replace)
fil=data %>% filter(City=="del")
print("Filtered rows:")
print(fil)
cols=data %>% select(Name,Age)
print("Selected clos:")
print(cols)
addcol=data %>% mutate(Bonus=Sal*0.1)
print("Added col:")
print(addcol)
arr=data %>% arrange(Age)
print("Age order:")
print(arr)
desage=data %>% arrange(desc(Age))
print("Age order:")
print(desage)
group=data %>% group_by(City) %>% summarize(Avgsal=mean(Sal))
print("Summarize:")
print(group)


