data(mtcars)
model_all=lm(mpg~.,data=mtcars)
summary(model_all)
v=cor(mtcars$mpg,mtcars[, -1])
print(v)
model=lm(mpg~cyl+hp+wt+disp+carb,data=mtcars)
summary(model)
par(mfrow=c(2,2))
plot(model)
par(mfrow=c(1,1))
pred=predict(model)
plot(mtcars$mpg,pred,main="Actual vs predicted",xlab="actual",ylab="Predicted",col="blue",pch=19)
abline(0,1,col="black",lwd=2)
coefs=coef(model)[-1]
print(coefs)
barplot(coefs,main="Coeffients",ylab="Coe value",col=ifelse(coefs>0,"pink","green"))
abline(h=0,col="black",lwd=2)